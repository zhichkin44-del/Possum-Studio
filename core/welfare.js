// Благополучие зверька выше контента: свет не просим, вспышку отмечаем.
export function welfareNotes(a) {
  const notes = [];
  if (a.dark) notes.push('Темно — это его время, свет ради съёмки не нужен. Снимайте в ночном (ИК) режиме камеры или поднесите телефон ближе.');
  if ((a.flash ?? []).length) notes.push('Похоже на вспышку или резкий свет. У поссумов чувствительные глаза: снимайте без вспышки, такой ролик лучше не выкладывать.');
  return notes;
}
