// Благополучие зверька выше контента: свет не просим, вспышку отмечаем.
// Совет зависит от вида ролика, чтобы в постах не стоял один и тот же абзац.
const BY_KIND = {
  top5: 'Это нарезка того, что уже снято: ничего не нужно повторять или разыгрывать заново.',
  day: 'Днём зверёк спит: днём снимайте только издалека и не будите его ради кадра.',
  beforeAfter: 'Не будите зверька ради кадра «потом» — снимайте, когда он проснётся сам.',
  calm: 'Спокойные кадры снимайте с расстояния: не трогайте и не перекладывайте зверька ради ракурса.',
  asmr: 'Кормите как обычно, в привычное время: не меняйте еду и кормление ради звука.',
  series: 'Серия — из того, что уже снято: не устраивайте занятие специально для съёмки.',
};

export function welfareNotes(a) {
  const notes = [];
  if (a.dark) notes.push('Темно — это его время, свет ради съёмки не нужен. Снимайте в ночном (ИК) режиме камеры, со штатива и на расстоянии; спящего не будите.');
  if (a.kind && BY_KIND[a.kind]) notes.push(BY_KIND[a.kind]);
  else if (!a.dark && a.always) notes.push('Снимайте, когда зверёк сам проснулся и занят своими делами: без вспышки, со штатива, не будите и не просите повторить.');
  if ((a.flash ?? []).length) notes.push('Похоже на вспышку или резкий свет. У ночных зверьков чувствительные глаза: снимайте без вспышки, такой ролик лучше не выкладывать.');
  return notes;
}
